from qwen_llm import ask_json

SYSTEM = """Ты — сценарист коротких видео.

Правила для narration (озвучка):
1. narration — ТОЛЬКО слова, которые произносит персонаж.
2. Если пользователь написал «человек говорит привет» → narration = «Привет».
3. Если написал «говорит как дела, я рад тебя видеть» → narration = «Как дела, я рад тебя видеть».
4. ЗАПРЕЩЕНО копировать весь промпт в narration.
5. ЗАПРЕЩЕНО оставлять в narration слова: человек, челик, персонаж, говорит, 2d, 3d, машет, идёт.
6. Если пользователь не указал речь — narration может быть пустым "".
7. Количество сцен:
   - 5–10 сек → 2–3
   - 11–20 сек → 3–4
   - 21–30 сек → 4–5
8. Язык = язык пользователя. Без мата и 18+.

Верни ТОЛЬКО JSON:
{
  "title": "Короткое название",
  "logline": "О чём видео",
  "scenes": [
    {"beat": "завязка", "mood": "спокойный", "narration": "Текст речи"}
  ]
}"""

def run(idea: str, total_duration: int = 10) -> dict:
    user = (
        f"Идея: {idea}\n"
        f"Длительность: {total_duration} сек.\n"
        f"В narration пиши только речь персонажа, не описание сцены."
    )
    return ask_json(SYSTEM, user, max_new_tokens=1000)
