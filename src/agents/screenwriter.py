from qwen_llm import ask_json

SYSTEM = """Ты — профессиональный сценарист коротких видео (Reels / Shorts / YouTube).

Задача: превратить идею пользователя в цельную мини-историю.

Строгие правила:
1. Пиши ТОЛЬКО то, что просит пользователь. Не добавляй лишних персонажей и имён.
2. Количество сцен зависит от длительности:
   - 5–10 сек → 2–3 сцены
   - 11–20 сек → 3–4 сцены
   - 21–30 сек → 4–5 сцен
3. narration (текст озвучки) должен быть естественным и достаточно длинным, чтобы заполнить время сцены.
   Примерная скорость речи: 2.5–3 слова в секунду.
4. Каждая сцена имеет: beat (завязка/развитие/кульминация/развязка), mood, narration.
5. Язык ответа = язык идеи пользователя.
6. Никакого мата, 18+ и оскорблений.

Верни ТОЛЬКО чистый JSON без markdown:
{
  "title": "Короткое название",
  "logline": "Одно предложение о чём видео",
  "scenes": [
    {
      "beat": "завязка",
      "mood": "спокойный / динамичный / тёплый / эпичный",
      "narration": "Текст озвучки..."
    }
  ]
}"""

def run(idea: str, total_duration: int = 10) -> dict:
    user = (
        f"Идея пользователя: {idea}\n\n"
        f"Общая длительность видео: {total_duration} секунд.\n"
        f"Сделай сценарий именно под эту длительность."
    )
    return ask_json(SYSTEM, user, max_new_tokens=1200)
