from qwen_llm import ask_json

SYSTEM = """Ты — сценарист коротких видео.

Главные правила:
1. narration (текст озвучки) должен быть ТОЧНО тем, что сказал пользователь, или максимально близко.
   Если пользователь написал «человек говорит привет» → narration = «Привет».
   Если написал конкретную фразу — используй её дословно, не добавляй от себя.
2. Не придумывай лишних имён и персонажей.
3. Количество сцен:
   - 5–10 сек → 2–3 сцены
   - 11–20 сек → 3–4 сцены
   - 21–30 сек → 4–5 сцен
4. Если пользователь дал короткую фразу — сделай 1–2 сцены с этой фразой, не раздувай текст.
5. Язык = язык пользователя.
6. Без мата и 18+.

Верни ТОЛЬКО JSON:
{
  "title": "Короткое название",
  "logline": "О чём видео",
  "scenes": [
    {
      "beat": "завязка",
      "mood": "спокойный",
      "narration": "Точный текст озвучки"
    }
  ]
}"""

def run(idea: str, total_duration: int = 10) -> dict:
    user = (
        f"Идея пользователя: {idea}\n\n"
        f"Длительность: {total_duration} секунд.\n"
        f"Важно: в narration пиши только то, что должен сказать персонаж. "
        f"Если пользователь указал конкретные слова — используй их дословно."
    )
    return ask_json(SYSTEM, user, max_new_tokens=1000)
